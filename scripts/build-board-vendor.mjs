#!/usr/bin/env node
/**
 * Writes the third-party files the public board page needs into <board>/vendor, so the page makes no
 * request to any other site (no CDN, no fonts host: nothing for a visitor's browser to tell a third party).
 *
 *   node scripts/build-board-vendor.mjs --opencharts <clone of OpenCharts> --fontawesome <npm package dir>
 *
 *   --board        the board repo folder (default ../GJUBoard)
 *   --opencharts   a checkout of https://github.com/Hamza928505/OpenCharts
 *   --fontawesome  the unpacked npm package @fortawesome/fontawesome-free (its `package` folder)
 *
 * SweetAlert2 and SheetJS come from this repo's node_modules. OpenCharts is bundled and minified into one
 * module placed where its own loader expects (js/studio/), next to the Chart.js file it loads on demand.
 * Nothing from the downloaded folders is executed: they are read and copied.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

import { build } from "esbuild";

import { ROOT } from "../lib/content.mjs";

const require = createRequire(import.meta.url);
const flag = (name) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : undefined; };
const board = path.resolve(ROOT, flag("board") || "../GJUBoard");
const openCharts = flag("opencharts") && path.resolve(flag("opencharts"));
const fontAwesome = flag("fontawesome") && path.resolve(flag("fontawesome"));
if (!openCharts || !fontAwesome) { console.error("Both --opencharts and --fontawesome are required. See the top of this file."); process.exit(1); }

const vendor = path.join(board, "vendor");
const put = (from, to) => { fs.mkdirSync(path.dirname(path.join(vendor, to)), { recursive: true }); fs.copyFileSync(from, path.join(vendor, to)); };
const version = (file) => JSON.parse(fs.readFileSync(file, "utf8")).version;
const notes = [];

// ---- OpenCharts: one minified module, with Chart.js beside it
await build({
  stdin: { contents: "export { render, getChart, newSpec } from './js/opencharts.js';", resolveDir: openCharts, loader: "js" },
  bundle: true, minify: true, format: "esm", target: "es2020", legalComments: "none", logLevel: "warning", logOverride: { "duplicate-object-key": "silent" }, // OpenCharts repeats a shorthand `color` in utils/data.js: harmless, same value
  outfile: path.join(vendor, "opencharts", "js", "studio", "oc.js"),
});
put(path.join(openCharts, "lib", "chart.umd.min.js"), "opencharts/lib/chart.umd.min.js");
put(path.join(openCharts, "LICENSE"), "opencharts/LICENSE");
put(path.join(openCharts, "THIRD-PARTY-NOTICES.md"), "opencharts/THIRD-PARTY-NOTICES.md");
notes.push(`| OpenCharts | ${version(path.join(openCharts, "package.json"))} | MIT | https://github.com/Hamza928505/OpenCharts, bundled by scripts/build-board-vendor.mjs; Chart.js 4.4.1 (MIT) is loaded on demand from opencharts/lib |`);

// ---- SweetAlert2 and SheetJS, from this repo's dependencies
const swal = path.dirname(require.resolve("sweetalert2/package.json"));
put(path.join(swal, "dist", "sweetalert2.all.min.js"), "sweetalert2/sweetalert2.all.min.js");
put(path.join(swal, "LICENSE"), "sweetalert2/LICENSE");
notes.push(`| SweetAlert2 | ${version(path.join(swal, "package.json"))} | MIT | https://sweetalert2.github.io/ |`);

const xlsx = path.dirname(require.resolve("xlsx/package.json"));
put(path.join(xlsx, "dist", "xlsx.full.min.js"), "xlsx.full.min.js");
notes.push(`| SheetJS Community Edition | ${version(path.join(xlsx, "package.json"))} | Apache-2.0 | https://sheetjs.com/, builds the .xlsx files in the browser |`);

// ---- Font Awesome Free: the solid icon font only
for (const css of ["fontawesome.min.css", "solid.min.css"]) put(path.join(fontAwesome, "css", css), `fontawesome/css/${css}`);
put(path.join(fontAwesome, "webfonts", "fa-solid-900.woff2"), "fontawesome/webfonts/fa-solid-900.woff2");
put(path.join(fontAwesome, "LICENSE.txt"), "fontawesome/LICENSE.txt");
notes.push(`| Font Awesome Free (solid) | ${version(path.join(fontAwesome, "package.json"))} | Icons CC BY 4.0, font SIL OFL 1.1, code MIT | https://fontawesome.com/license/free |`);

fs.writeFileSync(path.join(vendor, "README.md"), `# Vendored files

Third-party files the page serves itself, so a visitor's browser contacts no other site.
Generated by \`scripts/build-board-vendor.mjs\` in the private runner repository; do not edit by hand.

| Library | Version | Licence | Source |
|---|---|---|---|
${notes.join("\n")}

Each folder carries its own licence text.
`);
console.log(`Vendor files written to ${vendor}`);
for (const line of notes) console.log(" ", line.split("|")[1].trim(), line.split("|")[2].trim());
